  const languageButtons = Array.from(document.querySelectorAll("[data-language]"));
  window.museuI18n = { translations };

  const setLanguage = (language) => {
    const translation = translations[language];
    document.documentElement.lang = translation.locale;
    document.documentElement.dataset.language = language;
    const titleElement = document.querySelector("title");
    document.title = titleElement.dataset.i18n
      ? translation.ui[titleElement.dataset.i18n]
      : translation.pageTitle;
    const descriptionMeta = document.querySelector('meta[name="description"]');
    descriptionMeta.content = descriptionMeta.dataset.i18n
      ? translation.ui[descriptionMeta.dataset.i18n]
      : translation.pageDescription;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = translation.ui[element.dataset.i18n];
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      element.alt = translation.ui[element.dataset.i18nAlt];
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", translation.ui[element.dataset.i18nAriaLabel]);
    });
    document.querySelectorAll("[data-i18n-aria-roledescription]").forEach((element) => {
      element.setAttribute("aria-roledescription", translation.ui[element.dataset.i18nAriaRoledescription]);
    });

    languageButtons.forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.language === language));
    });

    document.dispatchEvent(new CustomEvent("museu:languagechange", { detail: { language } }));
  };

  languageButtons.forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
  });

  setLanguage("pt");
